"""Reasoning-effort sweep (exploratory; Can's go 2026-10-28): error rates on the 500 frozen standard positions of the
Nackgammon paired test, under the paired test's frozen rules (tools/v3/nack_paired_score.py: 2-ply losses, an
invalid/failed/timed-out answer scores the position's Random error; §10.14(h): an answer cut off at the output limit
is invalid, counted in its own column, with a sensitivity check that leaves those positions out; answers past 32,768
output tokens from runs that sent no limit are flagged and keep their scores). Plays no model.

    python3 tools/v3/effort_sweep_score.py > "mailbox/Reasoning sweep - results 2026-10-28.md"

Rows: every setup in smoke/effort-sweep.db (leagues/effort-sweep.json) plus, as partners, the standard answers of the
same models already in the paired test (smoke/nack-paired.db). Intervals: 95% bootstrap over positions, 10,000
resamples, one index set shared by every row (seed h("bootstrap:effort-sweep")).
"""

import re
import sys

import numpy as np

sys.path.insert(0, "tools/v3")
import nack_paired_score as n  # noqa: E402

# Display effort of the paired-test setups (database name -> (model, effort, route)); the relabel changed display
# names only (Can, 2026-10-28).
PAIRED = {
    "GPT-6 Astra (on)": ("GPT-6 Astra", "medium", "Codex"),
    "GPT-6.1 Sol (low)": ("GPT-6.1 Sol", "low", "Codex"),
    "GPT-6.1 Sol (high)": ("GPT-6.1 Sol", "high", "Codex"),
    "GPT-6.1 Terra": ("GPT-6.1 Terra", "low", "OpenRouter (OpenAI endpoint)"),
    "Claude Sonnet 5.5 (low)": ("Claude Sonnet 5.5", "low", "Claude"),
    "Claude Fable 5.1 (on)": ("Claude Fable 5.1", "high", "Claude"),
    "Gemini 3.8 Flash (low)": ("Gemini 3.8 Flash", "low", "Antigravity"),
    "Gemini 4 Argon (off)": ("Gemini 4 Argon", "low", "Antigravity"),
    "Grok 4.7 (on)": ("Grok 4.7", "high", "xAI"),
}
ROUTE = {"chatgpt-subscription": "Codex", "claude-subscription": "Claude", "antigravity-subscription": "Antigravity",
         "xai-subscription": "xAI"}
ORDER = ["none", "minimal", "low", "medium", "high", "xhigh", "max"]


def rows_of(d, setups, std):
    out = {}
    cut = d.cutoff()
    past = d.past_limit_no_limit_sent()
    for s in setups:
        a = d.answers.get(s, {})
        if not all(p in a for p in std):
            continue
        loss, ok, bad = [], [], 0
        for p in std:
            x, valid, _ = d.outcome(s, p)
            if not valid:
                bad += 1
                x = d.scores[p]["random"]
            loss.append(500 * x)
            ok.append(p not in cut.get(s, set()))
        out[s] = {"loss": np.array(loss), "ok": np.array(ok, dtype=float), "invalid": bad,
                  "cut": len(cut.get(s, set()) & set(std)), "past": len(past.get(s, set()) & set(std)),
                  "out_tok": float(np.mean([a[p]["output_tokens"] or 0 for p in std])),
                  "req_s": float(np.median([(a[p]["request_ms"] or 0) / 1000 for p in std])),
                  "cost": float(sum(a[p]["cost_usd"] or 0 for p in std))}
    return out


def main():
    sweep = n.Data(db="smoke/effort-sweep.db", roster="leagues/effort-sweep.json")
    paired = n.Data()
    std = [p["standard"] for p in paired.pairs]
    main200 = [p["standard"] for p in paired.main]
    rows = {}
    for d, names, kind in ((sweep, sweep.setups, "sweep"), (paired, [s for s in PAIRED if s in paired.setups], "paired")):
        for s, r in rows_of(d, names, std).items():
            if kind == "paired":
                model, effort, route = PAIRED[s]
            else:
                m = re.match(r"(.*) \(([^)]*)\)$", s)
                model, effort = m.group(1), m.group(2)
                route = ROUTE.get(d.players[s].get("provider"), d.players[s].get("provider"))
            rows[s] = dict(r, model=model, effort=effort, route=route, source=kind)
    idx = n.rng_for("effort-sweep").integers(0, len(std), size=(n.B, len(std)))
    m_idx = [std.index(p) for p in main200]
    print("# Reasoning-effort sweep: results (exploratory, 2026-10-28)\n")
    print("Generated by `tools/v3/effort_sweep_score.py` (frozen rules of the paired test; exploratory, no test). "
          "Error rate (PR) = 500 × mean GNUbg 2-ply loss on the 500 frozen **standard** positions of the Nackgammon "
          "paired test (prompt bg-v3-std-notable; not comparable with league error rates). Rows from the sweep "
          "(`smoke/effort-sweep.db`) and, as partners, the same models' standard answers from the paired test. "
          "Recorded cost is the API-equivalent on subscriptions (not money). Rows not yet run are absent.\n")
    print("| Model | Effort sent | Route | Source | PR, 500 [95%] | PR, main 200 | Invalid | Cut off at limit | "
          "PR without cut-off positions | Past 32,768, no limit sent | Output tok / dec | Median request s | "
          "Recorded cost |")
    print("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    key = lambda s: (rows[s]["model"], ORDER.index(rows[s]["effort"]) if rows[s]["effort"] in ORDER else 99,  # noqa: E731
                     rows[s]["route"])
    for s in sorted(rows, key=key):
        r = rows[s]
        boot = n.boot_means(r["loss"], np.ones(len(std)), idx)
        lo, hi = n.q(boot, 0.95)
        pr = r["loss"].mean()
        pr200 = r["loss"][m_idx].mean()
        prc = (r["loss"] * r["ok"]).sum() / r["ok"].sum()
        print(f"| {r['model']} | {r['effort']} | {r['route']} | {r['source']} | {pr:.2f} [{lo:.2f}, {hi:.2f}] | "
              f"{pr200:.2f} | {r['invalid']} | {r['cut']} | {prc:.2f} | {r['past']} | {r['out_tok']:.0f} | "
              f"{r['req_s']:.1f} | ${r['cost']:.2f} |")


if __name__ == "__main__":
    main()
