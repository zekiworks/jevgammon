#!/usr/bin/env python3
"""Refreshes the findings draft from the deployed site data (brief v12 B4). The site never shows it: findings are
published only after Ümit approves them; until then the home page says "Findings will be published after review."
Approved findings live in tools/site/content/findings.json with a machine check each (tools/site/findings.py),
the one-line lead-in too; checks.py reruns them before every deploy and a failing one stops the deploy.
The draft has one section per thread; the first answers the core question, at both risk margins (B6.6).

    python3 tools/site/findings_draft.py OUT_DIR DRAFT.md

Every number below is read from OUT_DIR/data/. League numbers stay inside their league.
"""

import json
import sys
from pathlib import Path

import findings as F


def load(out: Path, rel: str):
    return json.loads((out / "data" / rel).read_text())


def er(q):
    return f"{q['error_rate']:.1f} [{q['error_lo']:.1f}, {q['error_hi']:.1f}]"


def main():
    out, draft = Path(sys.argv[1]), Path(sys.argv[2])
    man = load(out, "manifest.json")
    lines = [f"# Findings draft (not published)", "",
             f"Generated by tools/site/findings_draft.py from the preview data: results {man['results']}, "
             f"data as of {man['data_as_of']}. The site shows no findings until Ümit approves a first set.", ""]
    published = F.published()
    stale = F.failures(out)
    lines += ["## Published findings to re-check", ""]
    lines += ([f"- {s}" for s in stale] or ["None published yet." if not published else "Every published finding still holds."]) + [""]
    shared = load(out, "v3/shared.json")
    leagues = sorted((out / "data/v3").glob("league-*.json"))
    programs = {(s["dataset"], s["name"]) for s in load(out, "setups.json")["setups"] if s.get("model_type") == "program"}
    lines += ["## 1. Decision quality under risk: can a model tell when a risk is worth taking?", "",
              "- Shared positions: Analysis pending.",
              "- Within each league (programs left out; league games are not paired, so league-to-league and "
              "setup-to-setup differences read as 'in league play'):"]
    for p in leagues:
        lg = json.loads(p.read_text())
        for m, label in (("main", "0.001 margin"), ("robust", "0.02 margin")):
            rows = [(n, s["risk"][m]) for n, s in lg["setups"].items() if (lg["dataset"], n) not in programs
                    and s["risk"][m].get("judgement") is not None]
            if not rows:
                lines.append(f"  - League {lg['id']} ({label}): risk judgement N/A for every model setup.")
                continue
            rows.sort(key=lambda r: -r[1]["judgement"])
            (a, ra), rest = rows[0], rows[1:]
            close = [n for n, r in rest if r["judgement_hi"] >= ra["judgement_lo"]]
            share = lambda x: f"{100 * x['share']:.1f}% ({x['n']:,.0f}/{x['den']:,.0f})"
            lines.append(f"  - League {lg['id']} ({lg['metric_status']}, {label}): best risk judgement {a} "
                         f"{ra['judgement']:.1f} [{ra['judgement_lo']:.1f}, {ra['judgement_hi']:.1f}] (risks found "
                         f"{share(ra['found'])}, right safety {share(ra['right_safety'])}); no clear difference in league "
                         f"play from: {', '.join(close) if close else 'none'}.")
            cautious = sum(1 for _, r in rows if r["missed"]["share"] is not None and r["needless"]["share"] is not None
                           and r["missed"]["share"] > r["needless"]["share"])
            lines.append(f"    Risk-call pattern ({label}): {cautious} of {len(rows)} model setups missed a larger share "
                         f"of Risk pays decisions than the share of Safety pays decisions where they took a needless risk.")
    lines += ["", "### Lowest move error (thread 1)", "",
              f"- Shared positions ({shared['standard']:,}): {shared['status']}. This is the only cross-league answer."]
    for p in leagues:
        lg = json.loads(p.read_text())
        rows = [(n, s["quality"]) for n, s in lg["setups"].items() if (lg["dataset"], n) not in programs
                and s["quality"].get("error_rate") is not None and not s["quality"].get("too_few")]
        rows.sort(key=lambda r: r[1]["error_rate"])
        if not rows:
            lines.append(f"  - League {lg['id']} ({lg['status']}): nothing scored yet.")
            continue
        best = rows[0]
        close = [n for n, q in rows[1:] if q["error_lo"] <= best[1]["error_hi"]]
        lines.append(f"  - League {lg['id']} ({lg['status']}, {lg['metric_status']}): lowest {best[0]} {er(best[1])}; "
                     f"no clear difference in league play from: {', '.join(close) if close else 'none'}.")
    lines += ["", "## 2. What the input adds", "",
              "- Earlier version (v1 prompt history, Method > Why it looks like this): computing each play's consequences "
              "in code cut the league error rate by about two thirds (league #6 to #7). No v3 ablation yet: Analysis pending."]
    lines += ["", "## 3. Confidence: does a model know when it is likely wrong?", "",
              "- Shared positions: Analysis pending. League decisions: 'confident and badly wrong' per league on the site."]
    lines += ["", "## 4. Cost: what quality costs, and what more reasoning buys", ""]
    v1 = load(out, "v1/v1-set.json")
    lines += ["- Reasoning, shared positions: Analysis pending (league games are not paired)."]
    for r in v1["reasoning"]:
        lines.append(f"- Earlier version (v1 set): {r['high']} vs {r['low']}: {r['diff']:+.1f} "
                     f"[{r['lo']:+.1f}, {r['hi']:+.1f}] over {r['positions']:,} positions: {r['verdict']}. "
                     f"Extra median time {r['extra_time_median']:+.1f} s per decision (a separate finding from move quality).")
    lines += ["- Which cheaper setup keeps the quality? Shared positions: Analysis pending.",
              "- Within each league ($ per 1,000 decisions where every decision is priced):"]
    for p in leagues:
        lg = json.loads(p.read_text())
        rows = [(n, s["quality"]) for n, s in lg["setups"].items()
                if s["quality"].get("usd_per_1000") is not None and s["quality"].get("error_rate") is not None
                and not s["quality"].get("too_few")]
        if not rows:
            lines.append(f"  - League {lg['id']}: no priced setups with enough decisions.")
            continue
        best = min(rows, key=lambda r: r[1]["error_rate"])
        keep = [r for r in rows if r[1]["error_lo"] <= best[1]["error_hi"]]
        cheap = min(keep, key=lambda r: r[1]["usd_per_1000"])
        lines.append(f"  - League {lg['id']} ({lg['metric_status']}): lowest error among priced setups {best[0]} "
                     f"{er(best[1])} at ${best[1]['usd_per_1000']:.3f}; cheapest with an overlapping interval: {cheap[0]} "
                     f"{er(cheap[1])} at ${cheap[1]['usd_per_1000']:.3f}.")
    draft.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    main()
