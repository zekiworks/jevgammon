"""Scores every legal play of every league decision at 2-ply, for the benchmark site.

Runs inside gnubg's embedded Python from the repo root, one shard per process. gnubg passes no
command-line arguments to the script, so they come from SCORE_PLAYS_ARGS:

    SCORE_PLAYS_ARGS="SNAP OUT_DIR SHARD SHARDS" gnubg -t -q -p tools/site/score_plays.py

SNAP is the site snapshot of v3.db (read-only); results go to OUT_DIR/s{SHARD}.db (tables `plays`
and `skipped`, schema below). tools/site/score.sh runs all shards.

A league decision is a `turns` row with decided_by 'model' or 'fallback' in a valid staged match
(`matches.valid = 1 AND stage IS NOT NULL`, in whatever league it was played: a setup that moves
leagues keeps its matches scored); plays.league_id is the match's shown league in `league_match_view`
(NULL when it is in no current league). A match held only by hidden leagues (`leagues.hidden`, an
early start for the next ladder round) is left for later: it is scored once a shown league holds it,
so it moves no setup's error rate before then. This shard takes those with turn_id % SHARDS == SHARD
that are not yet in plays
or skipped (incremental). For each one the legal plays are generated by tools/v3/rules.py (the
runner's order and notation); their count must equal turns.legal_count and the stored move must
lead to the play at turns.chosen_index, else the decision is skipped with the reason. Every legal
play is evaluated at 2-ply (cubeless money equity for the mover; a game-ending play scores its
points exactly), and described exactly as the runner showed it (tools/site/describe.py).
"""

import json
import os
import sqlite3
import sys

ROOT = os.getcwd()  # gnubg runs scripts without __file__
sys.path.insert(0, os.path.join(ROOT, "tools", "v3"))
sys.path.insert(0, os.path.join(ROOT, "tools", "site"))

from classify import phase, tag  # noqa: E402
from describe import describe_with_shots  # noqa: E402
from engine import PLY2, classify, equity  # noqa: E402
from rules import apply_notation, from_json, key, legal_plays  # noqa: E402

SCHEMA = """
CREATE TABLE IF NOT EXISTS plays (
    turn_id INTEGER PRIMARY KEY, league_id INTEGER, match_id INTEGER, game_id INTEGER, model TEXT,
    n INTEGER,          -- legal plays
    chosen INTEGER,     -- index of the play made, in legal order (= turns.chosen_index)
    best REAL,          -- best 2-ply equity among all legal plays
    loss REAL,          -- best - equity of the play made
    gnubg_class INTEGER, phase TEXT, tag TEXT,
    data TEXT);         -- JSON list in legal order: [notation, equity_2ply, hitting_rolls, description]
CREATE TABLE IF NOT EXISTS skipped (turn_id INTEGER PRIMARY KEY, reason TEXT);
"""
COMMIT_EVERY = 200


def skip_reason(plays, legal_count, chosen_index, move, pos):
    if len(plays) != legal_count:
        return f"{len(plays)} plays, stored {legal_count}"
    after = apply_notation(pos, move)
    if after is None:
        return f"chosen play {move} not legal"
    index = next((i for i, (_, r) in enumerate(plays) if key(r) == key(after)), None)
    if index is None:
        return f"chosen play {move} not legal"
    if index != chosen_index:
        return f"chosen play {move} is play {index}, stored chosen_index {chosen_index}"
    return None


def main():
    snap, out_dir, shard, shards = os.environ["SCORE_PLAYS_ARGS"].split()
    shard, shards = int(shard), int(shards)
    db = sqlite3.connect(f"file:{snap}?mode=ro", uri=True)
    out = sqlite3.connect(os.path.join(out_dir, f"s{shard}.db"))
    out.executescript(SCHEMA)
    done = {r[0] for r in out.execute("SELECT turn_id FROM plays UNION SELECT turn_id FROM skipped")}
    has_hidden = "hidden" in {r[1] for r in db.execute("PRAGMA table_info(leagues)")}
    shown = "COALESCE(l.hidden, 0) = 0" if has_hidden else "1"
    hidden_only = {r[0] for r in db.execute(f"""
        SELECT lm.match_id FROM league_match_view lm JOIN leagues l ON l.id = lm.league_id
        GROUP BY lm.match_id HAVING SUM({shown}) = 0""")}
    rows = db.execute(f"""
        SELECT t.id, (SELECT MIN(lm.league_id) FROM league_match_view lm JOIN leagues l ON l.id = lm.league_id
                      WHERE lm.match_id = m.id AND {shown}), g.match_id,
               t.game_id, p.name, t.turn_no, t.side, t.die1, t.die2, t.move, t.legal_count, t.chosen_index, t.position
        FROM turns t JOIN games g ON g.id = t.game_id JOIN matches m ON m.id = g.match_id
        JOIN players p ON p.id = CASE t.player WHEN 1 THEN m.player1 ELSE m.player2 END
        WHERE m.valid = 1 AND m.stage IS NOT NULL
          AND t.decided_by IN ('model', 'fallback') AND t.id % ? = ?
        ORDER BY t.id""", (shards, shard)).fetchall()
    db.close()
    n = pending = 0
    for tid, lid, mid, gid, model, turn_no, side, d1, d2, move, legal, chosen, position in rows:
        if tid in done or mid in hidden_only:
            continue
        pos = from_json(json.loads(position), side)
        plays = legal_plays(pos, d1, d2)
        reason = skip_reason(plays, legal, chosen, move, pos)
        if reason:
            out.execute("INSERT INTO skipped VALUES (?, ?)", (tid, reason))
            pending += 1
        else:
            data = []
            for play in plays:
                text, shots = describe_with_shots(pos, play)
                data.append([play[0], equity(play[1], PLY2), shots, text])
            best = max(d[1] for d in data)
            cls = classify(pos)
            ph = phase(pos, cls, turn_no)
            out.execute("INSERT INTO plays VALUES (?,?,?,?,?,?,?,?,?,?,?,?,?)",
                        (tid, lid, mid, gid, model, legal, chosen, best, best - data[chosen][1],
                         cls, ph, tag(pos, ph), json.dumps(data, separators=(",", ":"))))
            n += 1
            pending += 1
        if pending >= COMMIT_EVERY:
            out.commit()
            pending = 0
    out.commit()
    print(f"shard {shard}/{shards}: {n} decisions scored", flush=True)


main()
