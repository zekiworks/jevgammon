#!/usr/bin/env python3
"""Refreshes the findings draft from the deployed site data (brief B4). The site never shows it: findings are
published only after Ümit approves them; until then the home page says "Findings will be written when the
current leagues finish." Published findings to re-check live in tools/site/content/findings.json (none yet);
any that the new data no longer supports are listed at the top of the draft and in mailbox/.

    python3 tools/site/findings_draft.py OUT_DIR DRAFT.md

Every number below is read from OUT_DIR/data/. League numbers stay inside their league.
"""

import json
import sys
from pathlib import Path

from common import CONTENT, ROOT, THRESHOLDS as T


def load(out: Path, rel: str):
    return json.loads((out / "data" / rel).read_text())


def er(q):
    return f"{q['error_rate']:.1f} [{q['error_lo']:.1f}, {q['error_hi']:.1f}]"


def main():
    out, draft = Path(sys.argv[1]), Path(sys.argv[2])
    man = load(out, "manifest.json")
    lines = [f"# Findings draft (not published)", "",
             f"Generated by tools/site/findings_draft.py from the preview data: results {man['results']}, "
             f"data as of {man['data_as_of']}. The site shows no findings until Ümit approves a first set.", ""]
    # Each approved finding names the data value it rests on and the bound it needs, e.g.
    # {"text": "...", "data": "v3/league-1.json", "path": ["setups", "X", "quality", "error_hi"], "below": 30}.
    published = json.loads((CONTENT / "findings.json").read_text())["findings"] if (CONTENT / "findings.json").exists() else []
    stale = []
    for f in published:
        try:
            v = load(out, f["data"])
            for k in f["path"]:
                v = v[k]
            ok = (f.get("below") is None or v < f["below"]) and (f.get("above") is None or v > f["above"])
        except (KeyError, FileNotFoundError, TypeError):
            v, ok = None, False
        if not ok:
            stale.append(f"- {f['text']} (now {v!r} in data/{f['data']} {'/'.join(map(str, f['path']))})")
    lines += ["## Published findings to re-check", ""]
    lines += (stale or ["None published yet." if not published else "Every published finding still holds."]) + [""]
    shared = load(out, "v3/shared.json")
    lines += ["## 1. Lowest move error", "",
              f"- Shared positions ({shared['standard']:,}): {shared['status']}. This is the only cross-league answer.",
              "- Within each league (league decisions; not a cross-league ranking):"]
    leagues = sorted((out / "data/v3").glob("league-*.json"))
    programs = {(s["dataset"], s["name"]) for s in load(out, "setups.json")["setups"] if s.get("model_type") == "program"}
    lines[-1] += " Programs (Random, Safest, GNUbg weak) are left out."
    for p in leagues:
        lg = json.loads(p.read_text())
        rows = [(n, s["quality"]) for n, s in lg["setups"].items() if (lg["dataset"], n) not in programs
                and s["quality"].get("error_rate") is not None and not s["quality"].get("too_few")]
        rows.sort(key=lambda r: r[1]["error_rate"])
        if not rows:
            lines.append(f"  - League {lg['id']} ({lg['status']}): nothing scored yet.")
            continue
        best = rows[0]
        close = [n for n, q in rows[1:] if q["error_lo"] <= best[1]["error_hi"]]
        lines.append(f"  - League {lg['id']} ({lg['status']}, {lg['metric_status']}): lowest {best[0]} {er(best[1])}; "
                     f"intervals overlapping it: {', '.join(close) if close else 'none'}.")
    lines += ["", "## 2. Can models tell when a risk is worth taking?", "",
              "- Shared positions: Analysis pending.", "- Within each league (setups with at least "
              f"{T['min_decisions_per_cell']} decisions of each kind):"]
    for p in leagues:
        lg = json.loads(p.read_text())
        rows = [(n, s["risk"]) for n, s in lg["setups"].items() if (lg["dataset"], n) not in programs
                and s["risk"].get("takes_risk") is not None and not s["risk"]["risk_too_few"] and not s["risk"]["safety_too_few"]]
        if not rows:
            lines.append(f"  - League {lg['id']}: too few decisions.")
            continue
        rows.sort(key=lambda r: r[1]["needless_risk"] - r[1]["takes_risk"])
        a = rows[0]
        lines.append(f"  - League {lg['id']} ({lg['metric_status']}): widest gap between taking the risk when it pays "
                     f"and taking a needless one: {a[0]} ({100 * a[1]['takes_risk']:.1f}% vs "
                     f"{100 * a[1]['needless_risk']:.1f}%); narrowest: {rows[-1][0]} ({100 * rows[-1][1]['takes_risk']:.1f}% vs "
                     f"{100 * rows[-1][1]['needless_risk']:.1f}%).")
    v1 = load(out, "v1/v1-set.json")
    lines += ["", "## 3. Where does high reasoning help?", "",
              "- Shared positions: Analysis pending (league games are not paired)."]
    for r in v1["reasoning"]:
        lines.append(f"- Earlier version (v1 set): {r['high']} vs {r['low']}: {r['diff']:+.1f} "
                     f"[{r['lo']:+.1f}, {r['hi']:+.1f}] over {r['positions']:,} positions: {r['verdict']}. "
                     f"Extra median time {r['extra_time_median']:+.1f} s per decision (a separate finding from move quality).")
    lines += ["", "## 4. Which cheaper setup keeps the quality?", "", "- Shared positions: Analysis pending.",
              "- Within each league ($ per 1,000 decisions where every decision is priced):"]
    for p in leagues:
        lg = json.loads(p.read_text())
        rows = [(n, s["quality"]) for n, s in lg["setups"].items()
                if s["quality"].get("usd_per_1000") is not None and s["quality"].get("error_rate") is not None
                and not s["quality"].get("too_few")]
        if not rows:
            lines.append(f"  - League {lg['id']}: no priced setups with enough decisions.")
            continue
        best = min(rows, key=lambda r: r[1]["error_rate"])
        keep = [r for r in rows if r[1]["error_lo"] <= best[1]["error_hi"]]
        cheap = min(keep, key=lambda r: r[1]["usd_per_1000"])
        lines.append(f"  - League {lg['id']} ({lg['metric_status']}): lowest error among priced setups {best[0]} "
                     f"{er(best[1])} at ${best[1]['usd_per_1000']:.3f}; cheapest with an overlapping interval: {cheap[0]} "
                     f"{er(cheap[1])} at ${cheap[1]['usd_per_1000']:.3f}.")
    draft.write_text("\n".join(lines) + "\n")
    flag = ROOT / "mailbox/Backgammon site - findings to re-check.md"
    if stale:
        flag.write_text("# Published findings the new data no longer supports\n\n" + "\n".join(stale) + "\n")
    else:
        flag.unlink(missing_ok=True)


if __name__ == "__main__":
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    main()
